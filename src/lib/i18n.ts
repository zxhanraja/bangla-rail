export function getStationDisplayName(station: { name: string; nameBn?: string | null; code: string }, lang: Language): string {
  if (lang === 'bn' && station.nameBn) {
    return `${station.nameBn} (${station.code})`;
  }
  return `${station.name} (${station.code})`;
}
