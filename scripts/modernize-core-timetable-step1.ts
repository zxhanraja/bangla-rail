async function main() {
  console.log(`Checking and upserting ${MASTER_STATIONS.length} canonical stations...`);
  let created = 0;
  let updated = 0;

  for (const st of MASTER_STATIONS) {
    const existing = await prisma.station.findUnique({ where: { code: st.code } });
    if (!existing) {
      await prisma.station.create({
        data: {
          code: st.code,
          name: st.name,
          nameBn: st.nameBn,
          zone: st.zone,
          division: st.division,
          district: st.district,
          lat: st.lat || null,
          lng: st.lng || null,
          status: 'OPERATIONAL',
          sourceUrl: st.zone === 'SER' ? 'https://ser.indianrailways.gov.in/' : 'https://er.indianrailways.gov.in/',
          verifiedAt: new Date(),
        }
      });
      created++;
    } else {
      await prisma.station.update({
        where: { code: st.code },
        data: {
          name: st.name,
          nameBn: st.nameBn,
          zone: st.zone,
          division: st.division,
          district: st.district,
          lat: st.lat || existing.lat,
          lng: st.lng || existing.lng,
          status: 'OPERATIONAL',
          verifiedAt: new Date(),
        }
      });
      updated++;
    }
  }

  console.log(`✅ Station check complete! Created: ${created}, Updated: ${updated}`);
}

main().catch(console.error).finally(() => prisma.$disconnect());

