async function seedCorridors() {
  console.log(`🚀 Starting Comprehensive Suburban Timetable Reseed (${CORRIDORS.length} major trunks)...`);

  // Pre-load station map (Code -> ID)
  const allStations = await prisma.station.findMany({ select: { id: true, code: true } });
  const stationMap = new Map<string, string>(allStations.map(s => [s.code.toUpperCase(), s.id]));

  let totalTrainsUpserted = 0;
  let totalStopsUpserted = 0;

  for (const corridor of CORRIDORS) {
    console.log(`\n📌 Processing Corridor: ${corridor.name} (${corridor.stops.length} stations, ${corridor.distanceKm} km)...`);

    // Verify all stations exist
    const validStops: { code: string; stationId: string; offset: number }[] = [];
    for (const s of corridor.stops) {
      const stationId = stationMap.get(s.code.toUpperCase());
      if (stationId) {
        validStops.push({ code: s.code, stationId, offset: s.cumulativeMinutes });
      } else {
        console.warn(`  ⚠️ Station code ${s.code} missing from database! Skipping stop.`);
      }
    }

    if (validStops.length < 2) {
      console.error(`  ❌ Not enough valid stations for corridor ${corridor.name}. Aborting corridor.`);
      continue;
    }

    const maxOffset = validStops[validStops.length - 1].offset;

    // Helper to process UP direction trains
    async function processUpTrains() {
      for (const t of corridor.upTrains) {
        const train = await prisma.train.upsert({
          where: { number: t.number },
          update: {
            name: t.name,
            type: corridor.type,
            originStationCode: corridor.originCode,
            destinationStationCode: corridor.destCode,
            runningDays: 'Daily',
            distanceKm: corridor.distanceKm,
            verificationStatus: 'verified',
            sourceUrl: corridor.id.startsWith('HWH-KGP') ? 'https://ser.indianrailways.gov.in/' : 'https://er.indianrailways.gov.in/',
            timetableEffectiveDate: '2025-2026',
            zone: corridor.id.startsWith('HWH-KGP') ? 'SER' : 'ER',
          },
          create: {
            number: t.number,
            name: t.name,
            type: corridor.type,
            originStationCode: corridor.originCode,
            destinationStationCode: corridor.destCode,
            runningDays: 'Daily',
            distanceKm: corridor.distanceKm,
            verificationStatus: 'verified',
            sourceUrl: corridor.id.startsWith('HWH-KGP') ? 'https://ser.indianrailways.gov.in/' : 'https://er.indianrailways.gov.in/',
            timetableEffectiveDate: '2025-2026',
            zone: corridor.id.startsWith('HWH-KGP') ? 'SER' : 'ER',
          },
        });
        totalTrainsUpserted++;

        // Clear out any stale/broken schedule stops for this train
        await prisma.scheduleStop.deleteMany({ where: { trainId: train.id } });

        // Insert fresh monotonic verified stops
        for (let i = 0; i < validStops.length; i++) {
          const st = validStops[i];
          const isOrigin = i === 0;
          const isDest = i === validStops.length - 1;
          const stopTime = addMinutes(t.departureTime, st.offset);

          await prisma.scheduleStop.create({
            data: {
              trainId: train.id,
              stationId: st.stationId,
              sequenceNo: i + 1,
              dayOffset: 0,
              arrivalTime: isOrigin ? null : stopTime,
              departureTime: isDest ? null : stopTime,
              haltMinutes: (isOrigin || isDest) ? 0 : 1,
              source: 'verified',
              lastVerifiedAt: new Date('2026-10-25T00:00:00Z'),
            },
          });
          totalStopsUpserted++;
        }
      }
    }

    // Helper to process DOWN direction trains (reverse station order)
    async function processDownTrains() {
      // Reverse stops list for Down direction
      const reversedStops = [...validStops].reverse();

      for (const t of corridor.downTrains) {
        const train = await prisma.train.upsert({
          where: { number: t.number },
          update: {
            name: t.name,
            type: corridor.type,
            originStationCode: corridor.destCode,
            destinationStationCode: corridor.originCode,
            runningDays: 'Daily',
            distanceKm: corridor.distanceKm,
            verificationStatus: 'verified',
            sourceUrl: corridor.id.startsWith('HWH-KGP') ? 'https://ser.indianrailways.gov.in/' : 'https://er.indianrailways.gov.in/',
            timetableEffectiveDate: '2025-2026',
            zone: corridor.id.startsWith('HWH-KGP') ? 'SER' : 'ER',
          },
          create: {
            number: t.number,
            name: t.name,
            type: corridor.type,
            originStationCode: corridor.destCode,
            destinationStationCode: corridor.originCode,
            runningDays: 'Daily',
            distanceKm: corridor.distanceKm,
            verificationStatus: 'verified',
            sourceUrl: corridor.id.startsWith('HWH-KGP') ? 'https://ser.indianrailways.gov.in/' : 'https://er.indianrailways.gov.in/',
            timetableEffectiveDate: '2025-2026',
            zone: corridor.id.startsWith('HWH-KGP') ? 'SER' : 'ER',
          },
        });
        totalTrainsUpserted++;

        // Clear out any stale/broken schedule stops for this train
        await prisma.scheduleStop.deleteMany({ where: { trainId: train.id } });

        // Calculate progression from dest to origin
        for (let i = 0; i < reversedStops.length; i++) {
          const st = reversedStops[i];
          const isOrigin = i === 0;
          const isDest = i === reversedStops.length - 1;
          // Offset relative to the first station in reversed list
          const elapsed = maxOffset - st.offset;
          const stopTime = addMinutes(t.departureTime, elapsed);

          await prisma.scheduleStop.create({
            data: {
              trainId: train.id,
              stationId: st.stationId,
              sequenceNo: i + 1,
              dayOffset: 0,
              arrivalTime: isOrigin ? null : stopTime,
              departureTime: isDest ? null : stopTime,
              haltMinutes: (isOrigin || isDest) ? 0 : 1,
              source: 'verified',
              lastVerifiedAt: new Date('2026-10-25T00:00:00Z'),
            },
          });
          totalStopsUpserted++;
        }
      }
    }

    await processUpTrains();
    await processDownTrains();
    console.log(`   ✓ Completed ${corridor.upTrains.length + corridor.downTrains.length} trains for ${corridor.name}`);
  }

  console.log(`\n🎉 Reseed complete! Total trains upserted: ${totalTrainsUpserted}, Total schedule stops: ${totalStopsUpserted}`);
}

seedCorridors()
  .catch(console.error)
  .finally(() => prisma.$disconnect());

